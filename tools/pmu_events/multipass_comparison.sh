#!/usr/bin/env bash
# tools/pmu_events/multipass_comparison.sh
# T062 / FR-035, research D-15: the real-PMU record of the multi-pass
# collection on the development host.
#
# Usage: tools/pmu_events/multipass_comparison.sh [feature-build] [master-build]
#   feature-build  build tree of this feature (default: <repo>/build)
#   master-build   build tree of a pre-feature (master) checkout, used for the
#                  single-event reference runs; with none given the reference
#                  runs are recorded as skipped, with the reason.
# Env:   MIN_TIME   per-run --min-time in seconds (default 0.2)
#
# What it measures, in order:
#   1. the over-limit metric set of example/docs/metric_passes.cpp under
#      --metric-method=multiplex, passes and auto on one binary. That set is
#      programmableCounters() + 1 single-leaf columns, so it is over the
#      published limit on any host (FR-001);
#   2. a quiet-window noise marker: the same benchmark body with no metric
#      column attached, whose aggregate cv over its own repetitions is the
#      window-to-window noise of this host (SC-09);
#   3. one single-event reference run per event of the set on the master
#      build, for the per-event value comparison of SC-01.
# Wall time is recorded for every configuration, and the record carries the
# passes disclosure line and the per-column ratio= fields of each run.
#
# The transcript is rewritten whole at specs/024-multipass-collection/results/
# multipass_comparison.md (stale_state: never append). A run that measures
# nothing is recorded, not hidden: the record states the host condition
# (perf_event_paranoid, load) beside the rows, and a run whose columns carry
# no count is named in the digest.
#
# This is a documented measurement, not a CI gate (FR-035): it is registered
# with neither CMake nor CTest, and no workflow runs it or depends on its host.
#
# Exit 0 once the record is written. Exit 1 on a usage failure (a build tree
# with no binary to run).

set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd -P)
REPO_ROOT=$(cd "$SCRIPT_DIR/../.." && pwd -P)

FEATURE_BUILD=${1:-"$REPO_ROOT/build"}
MASTER_BUILD=${2:-}
MIN_TIME=${MIN_TIME:-0.2}

OUT_DIR="$REPO_ROOT/specs/024-multipass-collection/results"
OUT="$OUT_DIR/multipass_comparison.md"

# The over-limit set ships as an example (FR-001 shape): one metric column per
# event leaf, sized to the published limit plus one. The same leaf names are
# the reference events of the master runs.
SPLIT_BIN="$FEATURE_BUILD/example/docs_metric_passes"
QUIET_BIN="$FEATURE_BUILD/example/docs_counter_metrics"
REFERENCE_BIN="$MASTER_BUILD/example/docs_counter_metrics"
EVENTS=(cpu-cycles instructions branch-misses ref-cycles bus-cycles)

if [ ! -x "$SPLIT_BIN" ]; then
  echo "multipass_comparison.sh: no binary at $SPLIT_BIN (build the feature tree first)" >&2
  exit 1
fi
if [ ! -x "$QUIET_BIN" ]; then
  echo "multipass_comparison.sh: no binary at $QUIET_BIN" >&2
  exit 1
fi

WORKDIR=$(mktemp -d)
trap 'rm -rf "$WORKDIR"' EXIT
SECTIONS="$WORKDIR/sections.md"
DIGEST="$WORKDIR/digest.md"

# run_record <label> <binary> [arg...]: the section of one configuration: its
# command line, its verbatim stdout and stderr, its exit status and its wall
# time. A non-zero run is recorded like any other: this script judges nothing.
run_record() {
  local label=$1
  shift
  local started ended status=0 output
  started=$(date +%s%N)
  output=$("$@" 2>&1) || status=$?
  ended=$(date +%s%N)
  printf '### %s\n\n' "$label"
  printf '$ %s\n\n' "$*"
  printf '```\n%s\n```\n\n' "$output"
  printf 'exit=%s wall=%d ms\n\n' "$status" "$(( (ended - started) / 1000000 ))"
}

# host_line <label> <file>: a host fact, or the reason it is unreadable.
host_line() {
  local label=$1
  local file=$2
  if [ -r "$file" ]; then
    printf -- '- %s: `%s`\n' "$label" "$(tr -d '\n' <"$file")"
  else
    printf -- '- %s: `%s` is unreadable\n' "$label" "$file"
  fi
}

{
  printf '# Multi-pass collection: the real-PMU comparison (FR-035, SC-01, SC-09)\n\n'
  printf 'Generated by `tools/pmu_events/multipass_comparison.sh` at %s. Re-running\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
  printf 'the script rewrites this file. Nothing here is a CI gate: no CMake target\n'
  printf 'and no workflow references this script.\n\n'
  printf '## Host\n\n'
  printf -- '- hostname: `%s`\n' "$(hostname)"
  printf -- '- kernel: `%s`\n' "$(uname -srm 2>/dev/null || uname)"
  printf -- '- cpu: `%s`\n' "$(sed -n 's/^model name[[:space:]]*:[[:space:]]*//p' /proc/cpuinfo | head -1)"
  host_line 'perf_event_paranoid' /proc/sys/kernel/perf_event_paranoid
  printf -- '- uptime: `%s`\n' "$(uptime)"
  host_line 'load average' /proc/loadavg
  printf -- '- feature build: `%s`\n' "$FEATURE_BUILD"
  printf -- '- master build: `%s`\n\n' "${MASTER_BUILD:-none given}"

  printf '## The over-limit set under the three methods\n\n'
  printf 'The set is the %d event leaves of `example/docs/metric_passes.cpp`, one\n' "${#EVENTS[@]}"
  printf 'metric column each, attached as the published limit plus one.\n\n'
  for method in multiplex passes auto; do
    run_record "method=$method" "$SPLIT_BIN" --metric-method="$method" --min-time="$MIN_TIME"
  done

} >"$SECTIONS"

# The quiet run is captured on its own: its aggregate cv is the noise figure
# the digest prints, and no other section of the record has to be scanned.
QUIET_SECTION=$(run_record 'bare body, no metric column' "$QUIET_BIN" \
  --min-time="$MIN_TIME")
QUIET_CV=$(printf '%s\n' "$QUIET_SECTION" |
  sed -n 's/.*AGGREGATE.*cv= *\([0-9.]*\).*/\1/p' | head -1 || true)

{
  printf '## Quiet-window noise marker\n\n'
  printf 'The same benchmark body with no metric column attached. The family asks\n'
  printf 'for two repetitions in code and that count wins over `--repetitions`, so\n'
  printf 'the marker below is the `cv=` of those two windows.\n\n'
  printf 'That aggregate `cv=` is the window-to-window noise of this host: the\n'
  printf 'figure a `spread=` has to exceed to be a pass-split effect, not noise.\n\n'
  printf '%s\n\n' "$QUIET_SECTION"

  printf '## Single-event reference runs\n\n'
  printf 'One run per event of the set on the master build, the event alone in its\n'
  printf 'own group: the value each event reaches with no sharing at all.\n\n'
  if [ -n "$MASTER_BUILD" ] && [ -x "$REFERENCE_BIN" ]; then
    for event in "${EVENTS[@]}"; do
      run_record "reference $event" "$REFERENCE_BIN" --counter "cpu/$event" --min-time="$MIN_TIME"
    done
  else
    printf '`%s` holds no `example/docs_counter_metrics`: the reference runs were\n' "${MASTER_BUILD:-no master build given}"
    printf 'skipped. Re-run with the master build directory as the second argument.\n\n'
  fi
} >>"$SECTIONS"

{
  pass_lines=$(grep -E 'passes  method=' "$SECTIONS" || true)
  gapped_columns=$(grep -oE '[A-Za-z0-9_/.-]+= *-?[0-9.]+ ratio=[0-9.]+ scaled=[01] gap=1' "$SECTIONS" |
    sort -u || true)
  printf '## Digest\n\n'
  printf 'Passes disclosure lines, in run order:\n\n'
  printf '```\n'
  if [ -n "$pass_lines" ]; then
    printf '%s\n' "$pass_lines"
  else
    printf '(no passes disclosure line was printed)\n'
  fi
  printf '```\n\n'
  printf 'Quiet-window aggregate coefficient of variation: `%s`\n\n' "${QUIET_CV:-not printed}"
  printf 'Columns that carried no count, deduplicated. A `gap=1` beside a zero\n'
  printf 'value is the kernel withholding counts on this host over the window:\n\n'
  printf '```\n'
  if [ -n "$gapped_columns" ]; then
    printf '%s\n' "$gapped_columns"
  else
    printf '(every column of every run carried a count)\n'
  fi
  printf '```\n'
} >"$DIGEST"

mkdir -p "$OUT_DIR"
cat "$SECTIONS" "$DIGEST" >"$OUT"

echo "multipass_comparison.sh: wrote $OUT"
grep -E 'passes  method=' "$OUT" | sed 's/^/  /' || echo "  (no passes disclosure line)"
